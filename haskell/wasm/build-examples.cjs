// Run with Playwright installed and the static web directory served locally:
//   CRITICALVALUES_URL=http://localhost:8000 node haskell/wasm/build-examples.cjs
// Uses the same WASM/FLINT pipeline as arbitrary input, including H checks.
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch(process.env.CHROME_PATH ? {executablePath: process.env.CHROME_PATH} : {});
  try {
    const page = await browser.newPage();
    await page.goto(process.env.CRITICALVALUES_URL || 'http://localhost:8000/', {waitUntil: 'domcontentloaded'});
    const examples = await page.evaluate(async () => {
      const {pickBackend, solveWithFlint} = await import('./js/backend.js?v=background-1');
      const {loadParser, toWire} = await import('./js/parse.js?v=fast-start-1');
      await loadParser();
      const backend = await pickBackend();
      if (backend.name !== 'wasm') throw new Error('Example generation requires WASM');
      const examples = {};
      for (const button of document.querySelectorAll('.ex')) {
        const input = button.dataset.f;
        const result = await solveWithFlint(backend, toWire(input));
        if (!result.ok || !result.setups?.length || result.setups.some(s => s.HIrred !== true || !s.checks?.length || s.checks.some(c => !c.ok)))
          throw new Error('Example failed verification: ' + input);
        examples[input.replace(/\s+/g, '')] = result;
        examples[result.f.join(',')] = result;
      }
      return examples;
    });
    const out = path.join(__dirname, '../web/examples.js');
    fs.writeFileSync(out, '// Generated by wasm/build-examples.cjs using solveWithFlint; do not hand-edit.\nexport const examples = ' + JSON.stringify(examples) + ';\n');
    console.log('Verified examples:', Object.keys(examples).length / 2, 'bytes:', fs.statSync(out).size);
  } finally { await browser.close(); }
})().catch(e => {console.error(e); process.exitCode = 1;});
